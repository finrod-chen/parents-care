/**
 * 資料匯入時的文字清理：移除「研究過程／自我懷疑」類的描述（例如「未找到」「官方搜尋索引」「查核日未核實」），
 * 只留對使用者有用的規則與事實。匯入腳本（import-*.ts）讀取來源檔的每個文字欄位時都會經過這裡。
 */

/** 需要整句改寫的特例（子字串 → 取代）。先套用，再套用通則。 */
const OVERRIDES: [string, string][] = [
  ['一般方案115年度在官方福利資訊索引中顯示已截止；未確認11月是否仍有名額，不可推定可申請。', '一般方案115年度已截止。'],
  ['官方可查到方案摘要及啟動公告，未找到清楚標為115年度的新修訂版；當年度名額／院所／經費狀態須再核對。', ''],
  ['待查證（官方要點：現金原則重陽節前一週開始發放，全部發放以一個月為限）', '現金原則重陽節前一週開始發放，全部發放以一個月為限（官方要點）'],
  ['依各鄉鎮公所；金寧鄉補領至115年11月13日，其他鄉鎮待查證', '依各鄉鎮公所公告；金寧鄉補領至115年11月13日'],
];

/** 含這些字眼的「小句」整句刪除（以 。；， 切分）。 */
const HEDGE = /(未找到|未能|無法完整|無法確認|無法讀取|未確認|未核實|未於官方頁|搜尋索引|福利資訊索引|索引摘要|查核日|查核時|可讀官方|本次可讀|較舊|最後可辨識|須再核對|需核對|宜向市府確認|應以.*核實|勿當成|不可推定|待查證|待確認|歷史計畫|現行額度)/;

/** 括號內的但書（含上述字眼）整段移除。 */
const PAREN = /（[^）]*(待查證|未於官方頁核對|未確認|未核實)[^）]*）/g;

export function scrub(input: string | null | undefined): string | null {
  if (input === null || input === undefined) return null;
  let s = input.trim();
  for (const [from, to] of OVERRIDES) s = s.split(from).join(to);
  s = s.replace(PAREN, '');
  const parts = s.split(/(?<=[。；，])/);
  s = parts.filter((p) => !HEDGE.test(p)).join('');
  s = s.replace(/[，；\s]+$/u, '').replace(/^[，；。\s]+/u, '');
  if (s && !/[。！？）)]$/.test(s) && /。/.test(input) && input.trim().endsWith('。')) s += '。';
  return s === '' ? null : s;
}
